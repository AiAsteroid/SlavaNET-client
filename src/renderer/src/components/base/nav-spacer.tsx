import React from 'react'

// Пустое место в конце списка под плавающую капсулу.
//
// Нужен там, где прокручивает не оболочка, а сам список (Virtuoso): до его
// скроллера нам не дотянуться, и единственный честный способ дать запас —
// отдать списку подвал нужной высоты. Высота ровно та же, что отступ у
// обычных экранов, иначе два экрана кончались бы на разной высоте.
const NavSpacer: React.FC = () => (
  <div style={{ height: 'calc(var(--nav-space) - var(--nav-gap))' }} />
)

// Один набор свойств на все списки Virtuoso в приложении: прокрутка без
// полосы, растворение нижнего края, запас под капсулу подвалом — и граница
// области ровно на нижней кромке капсулы.
//
// ⚠️ marginBottom обязателен. Без него область доходит до края окна, и в
// полосе в 20px под панелью остаются строки, уже полностью растворённые
// маской, но по-прежнему ловящие нажатия: клик в пустоту под капсулой
// переключал бы сервер или открывал соединение. Ровно на этом уже обожглись
// в списке серверов (main.css, .sn-fade-bottom).
export const listScroll = {
  className: 'sn-scroll sn-fade-bottom',
  style: { marginBottom: 'var(--nav-gap)' },
  components: { Footer: NavSpacer }
} as const

export default NavSpacer
